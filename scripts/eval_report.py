"""Build docs/results/sql_eval.md from the saved runs in evaluation/runs/.

Every accuracy gets a 95% Wilson interval: with 37-56 questions, one question is 2-3
points, so differences smaller than the intervals are not evidence of anything.

usage: uv run python scripts/eval_report.py
"""

from __future__ import annotations

import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "evaluation" / "runs"

ABLATIONS = [
    ("all-v4", "Full pipeline: Qwen2.5-Coder-7B, schema retrieval, 2 correction rounds"),
    ("all-v4-repeat", "Same configuration, run again (run-to-run variation)"),
    ("all-v4-noretrieval", "Whole schema in every prompt (no retrieval)"),
    ("all-v4-nocorrect", "No self-correction (first query is final)"),
    ("all-v4-3b", "Smaller model: Qwen2.5-Coder-3B"),
]


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return 0.0, 0.0
    p = k / n
    centre = (p + z * z / (2 * n)) / (1 + z * z / n)
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return centre - half, centre + half


def load(label: str) -> tuple[dict, list[dict]]:
    s = json.loads((RUNS / f"{label}.summary.json").read_text())
    recs = [json.loads(x) for x in (RUNS / f"{label}.jsonl").read_text().splitlines()]
    return s, recs


def acc(recs: list[dict], split: str | None = None) -> str:
    rs = [r for r in recs if r["kind"] == "sql" and (split is None or r["split"] == split)]
    k = sum(r["correct"] for r in rs)
    lo, hi = wilson(k, len(rs))
    return f"{k}/{len(rs)} = {k / len(rs):.1%} ({lo:.0%}-{hi:.0%})"


def main() -> None:
    lines = ["# NL-to-SQL evaluation", "",
             "Execution accuracy on `evaluation/golden.yaml`: the generated query's result must "
             "match the gold query's result (see `src/analytics_copilot/eval/matching.py`). "
             "Brackets are 95% Wilson intervals. Generated by `scripts/eval_report.py`.", ""]

    s, recs = load("test-v3")
    lines += ["## Held-out result", "",
              "The test split (37 SQL questions + 8 refusals) was run once, after prompt work on "
              "the dev split only:", "",
              f"- Execution accuracy: **{acc(recs)}**",
              f"- Queries that executed: {s['executed_rate']:.0%}",
              f"- Refusals correct: {s['refusal_accuracy']:.0%} "
              f"({s['refusals_stopped_by']['intent']} stopped by intent rules, "
              f"{s['refusals_stopped_by']['none']} answered with fabricated data)",
              "",
              "Failures on that run led to three changes (table-less queries are now rejected; "
              "a 'physical store' definition; a rule to group time with date_trunc) and one "
              "scorer fix (years as 2024 or 2024-01-01). Numbers below include those changes and "
              "are **no longer held-out**: the test questions have been looked at.", ""]

    lines += ["## Ablations (all 56 SQL questions)", "",
              "| Configuration | Execution accuracy | Dev | Test | First attempt | Executed | "
              "Mean prompt tokens | p50 / p95 latency |", "|---|---|---|---|---|---|---|---|"]
    for label, desc in ABLATIONS:
        if not (RUNS / f"{label}.summary.json").exists():
            continue
        s, recs = load(label)
        sql = [r for r in recs if r["kind"] == "sql"]
        lines.append(
            f"| {desc} | {acc(recs)} | {acc(recs, 'dev').split(' (')[0]} | "
            f"{acc(recs, 'test').split(' (')[0]} | {s['first_attempt_accuracy']:.1%} | "
            f"{s['executed_rate']:.0%} | {s['mean_prompt_tokens']:,} | "
            f"{s['latency_p50_ms']:,} / {s['latency_p95_ms']:,} ms |")
        del sql

    s, recs = load("all-v4")
    lines += ["", "## By category (full pipeline)", "", "| Category | Correct |", "|---|---|"]
    for cat, v in s["by_category"].items():
        k = round(v["ex"] * v["n"])
        lines.append(f"| {cat} | {k}/{v['n']} |")

    lines += ["", f"Schema retrieval selected every table the gold query uses in "
              f"{s['retrieval_all_tables_found']:.0%} of questions, with "
              f"{s['mean_tables_selected']} tables on average out of 8.", "",
              "## Remaining failures (full pipeline)", "", "| Id | Question | What went wrong |",
              "|---|---|---|"]
    notes = json.loads((ROOT / "evaluation" / "failure_notes.json").read_text())
    for r in recs:
        if r["kind"] == "sql" and not r["correct"]:
            note = notes.get(r["id"], r["error"] or "")
            lines.append(f"| {r['id']} | {r['question']} | {note} |")
    out = ROOT / "docs" / "results" / "sql_eval.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
